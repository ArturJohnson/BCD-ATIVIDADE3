-- ---------------------------------------------------------------------
-- Tabelas de apoio (domínios)
-- ---------------------------------------------------------------------

CREATE TABLE especie (
    id_especie   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome         VARCHAR(40) NOT NULL UNIQUE
);

CREATE TABLE raca (
    id_raca      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome         VARCHAR(60) NOT NULL,
    id_especie   INTEGER NOT NULL,
    CONSTRAINT fk_raca_especie
        FOREIGN KEY (id_especie) REFERENCES especie (id_especie),
    CONSTRAINT uq_raca_nome_especie UNIQUE (nome, id_especie)
);

CREATE TABLE especialidade (
    id_especialidade INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome             VARCHAR(60) NOT NULL UNIQUE
);

-- ---------------------------------------------------------------------
-- Tutores e animais
-- ---------------------------------------------------------------------

CREATE TABLE tutor (
    id_tutor       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome           VARCHAR(100) NOT NULL,
    cpf            CHAR(11)     NOT NULL UNIQUE,
    telefone       VARCHAR(15),
    email          VARCHAR(100) UNIQUE,
    cidade         VARCHAR(60)  NOT NULL,
    data_cadastro  DATE         NOT NULL DEFAULT CURRENT_DATE
);

CREATE TABLE animal (
    id_animal        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome             VARCHAR(60)  NOT NULL,
    data_nascimento  DATE         NOT NULL,
    sexo             CHAR(1)      NOT NULL,
    peso_kg          NUMERIC(6,2) NOT NULL,
    id_tutor         INTEGER      NOT NULL,
    id_raca          INTEGER      NOT NULL,
    CONSTRAINT fk_animal_tutor
        FOREIGN KEY (id_tutor) REFERENCES tutor (id_tutor),
    CONSTRAINT fk_animal_raca
        FOREIGN KEY (id_raca)  REFERENCES raca (id_raca),
    CONSTRAINT ck_animal_sexo CHECK (sexo IN ('M', 'F')),
    CONSTRAINT ck_animal_peso CHECK (peso_kg > 0)
);

-- Relacionamento 1:1 com animal (a chave primária é também chave estrangeira)
CREATE TABLE microchip (
    id_animal      INTEGER PRIMARY KEY,
    numero         CHAR(15) NOT NULL UNIQUE,
    data_implante  DATE     NOT NULL,
    CONSTRAINT fk_microchip_animal
        FOREIGN KEY (id_animal) REFERENCES animal (id_animal)
        ON DELETE CASCADE
);

-- ---------------------------------------------------------------------
-- Veterinários
-- ---------------------------------------------------------------------

CREATE TABLE veterinario (
    id_veterinario  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome            VARCHAR(100) NOT NULL,
    crmv            VARCHAR(15)  NOT NULL UNIQUE,
    telefone        VARCHAR(15),
    ativo           BOOLEAN      NOT NULL DEFAULT TRUE
);

-- N:N entre veterinário e especialidade
CREATE TABLE veterinario_especialidade (
    id_veterinario   INTEGER NOT NULL,
    id_especialidade INTEGER NOT NULL,
    CONSTRAINT pk_veterinario_especialidade
        PRIMARY KEY (id_veterinario, id_especialidade),
    CONSTRAINT fk_ve_veterinario
        FOREIGN KEY (id_veterinario)   REFERENCES veterinario (id_veterinario)
        ON DELETE CASCADE,
    CONSTRAINT fk_ve_especialidade
        FOREIGN KEY (id_especialidade) REFERENCES especialidade (id_especialidade)
);

-- Dias da semana em que o veterinário atende (fato independente das
-- especialidades -> tabela própria, por causa da 4FN)
CREATE TABLE veterinario_dia_atendimento (
    id_veterinario  INTEGER NOT NULL,
    dia_semana      CHAR(3) NOT NULL,
    CONSTRAINT pk_veterinario_dia
        PRIMARY KEY (id_veterinario, dia_semana),
    CONSTRAINT fk_vd_veterinario
        FOREIGN KEY (id_veterinario) REFERENCES veterinario (id_veterinario)
        ON DELETE CASCADE,
    CONSTRAINT ck_vd_dia
        CHECK (dia_semana IN ('SEG', 'TER', 'QUA', 'QUI', 'SEX', 'SAB', 'DOM'))
);

-- ---------------------------------------------------------------------
-- Atendimento clínico
-- ---------------------------------------------------------------------

CREATE TABLE consulta (
    id_consulta     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_hora       TIMESTAMP     NOT NULL,
    motivo          VARCHAR(150)  NOT NULL,
    diagnostico     VARCHAR(200),
    valor           NUMERIC(8,2)  NOT NULL,
    status          VARCHAR(10)   NOT NULL DEFAULT 'AGENDADA',
    id_animal       INTEGER       NOT NULL,
    id_veterinario  INTEGER       NOT NULL,
    CONSTRAINT fk_consulta_animal
        FOREIGN KEY (id_animal)      REFERENCES animal (id_animal),
    CONSTRAINT fk_consulta_veterinario
        FOREIGN KEY (id_veterinario) REFERENCES veterinario (id_veterinario),
    CONSTRAINT ck_consulta_valor  CHECK (valor >= 0),
    CONSTRAINT ck_consulta_status CHECK (status IN ('AGENDADA', 'REALIZADA', 'CANCELADA'))
);

CREATE TABLE medicamento (
    id_medicamento  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome            VARCHAR(80)  NOT NULL UNIQUE,
    fabricante      VARCHAR(60)  NOT NULL,
    preco_unitario  NUMERIC(8,2) NOT NULL,
    estoque         INTEGER      NOT NULL DEFAULT 0,
    CONSTRAINT ck_medicamento_preco   CHECK (preco_unitario >= 0),
    CONSTRAINT ck_medicamento_estoque CHECK (estoque >= 0)
);

-- N:N entre consulta e medicamento (com atributos próprios da prescrição)
CREATE TABLE consulta_medicamento (
    id_consulta     INTEGER      NOT NULL,
    id_medicamento  INTEGER      NOT NULL,
    quantidade      INTEGER      NOT NULL,
    posologia       VARCHAR(100) NOT NULL,
    CONSTRAINT pk_consulta_medicamento
        PRIMARY KEY (id_consulta, id_medicamento),
    CONSTRAINT fk_cm_consulta
        FOREIGN KEY (id_consulta)    REFERENCES consulta (id_consulta)
        ON DELETE CASCADE,
    CONSTRAINT fk_cm_medicamento
        FOREIGN KEY (id_medicamento) REFERENCES medicamento (id_medicamento),
    CONSTRAINT ck_cm_quantidade CHECK (quantidade > 0)
);

-- ---------------------------------------------------------------------
-- Vacinação
-- ---------------------------------------------------------------------

CREATE TABLE vacina (
    id_vacina              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome                   VARCHAR(60)  NOT NULL UNIQUE,
    doenca_alvo            VARCHAR(120) NOT NULL,
    intervalo_reforco_dias INTEGER      NOT NULL,
    preco                  NUMERIC(8,2) NOT NULL,
    CONSTRAINT ck_vacina_intervalo CHECK (intervalo_reforco_dias > 0),
    CONSTRAINT ck_vacina_preco     CHECK (preco >= 0)
);

-- N:N entre animal e vacina (cada linha é uma aplicação concreta)
CREATE TABLE aplicacao_vacina (
    id_aplicacao    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_animal       INTEGER     NOT NULL,
    id_vacina       INTEGER     NOT NULL,
    id_veterinario  INTEGER     NOT NULL,
    data_aplicacao  DATE        NOT NULL,
    lote            VARCHAR(20) NOT NULL,
    CONSTRAINT fk_av_animal
        FOREIGN KEY (id_animal)      REFERENCES animal (id_animal),
    CONSTRAINT fk_av_vacina
        FOREIGN KEY (id_vacina)      REFERENCES vacina (id_vacina),
    CONSTRAINT fk_av_veterinario
        FOREIGN KEY (id_veterinario) REFERENCES veterinario (id_veterinario),
    CONSTRAINT uq_av_animal_vacina_data
        UNIQUE (id_animal, id_vacina, data_aplicacao)
);

-- ---------------------------------------------------------------------
-- Índices nas chaves estrangeiras mais consultadas
-- ---------------------------------------------------------------------

CREATE INDEX idx_animal_tutor         ON animal (id_tutor);
CREATE INDEX idx_animal_raca          ON animal (id_raca);
CREATE INDEX idx_consulta_animal      ON consulta (id_animal);
CREATE INDEX idx_consulta_veterinario ON consulta (id_veterinario);
CREATE INDEX idx_consulta_data        ON consulta (data_hora);
CREATE INDEX idx_av_animal            ON aplicacao_vacina (id_animal);
